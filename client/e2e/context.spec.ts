import { test, expect, type Page } from '@playwright/test'

async function setup(page: Page) {
  const csrf = async () => (await (await page.request.get('/api/v1/auth/csrf')).json()).token as string
  const registration = await page.request.post('/api/v1/auth/register', { headers: { 'X-CSRF-Token': await csrf() },
    data: { email: `context-ui-${crypto.randomUUID()}@example.test`, password: 'Context-Browser-Password1!', displayName: 'Context learner' } })
  expect(registration.status()).toBe(201)
  const token = await csrf()
  const episode = await page.request.post('/api/v1/work/episodes', { headers: { 'X-CSRF-Token': token },
    data: { title: 'Investigating copied state', setting: 'PersonalProject', eventDate: '2026-10-03', role: 'Developer', summary: 'Selected summary stays local.' } })
  expect(episode.status()).toBe(201)
  const id = (await episode.json()).id as string
  await page.goto(`/reflect/${id}`)
  await expect(page.getByRole('heading', { name: 'Investigating copied state' })).toBeVisible()
  await expect(page.getByText('Loading saved context…')).toBeHidden()
  return { id, csrf: token, root: `/api/v1/work/episodes/${id}/context` }
}
async function previewAndSave(page: Page) {
  await page.getByRole('button', { name: 'Preview selected context', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Disclosure preview' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save source snapshot', exact: true })).toBeDisabled()
  await page.getByLabel('I reviewed these selected fields and recipients for this source version.').check()
  await page.getByRole('button', { name: 'Save source snapshot', exact: true }).click()
}

test('source snapshots, corrections and exact confirmation keep provenance and recover failed saves', async ({ page }, info) => {
  const account = await setup(page)
  const supplied = '// preserve spaces  \n<script>window.contextExecuted = true</script>\nconst sample = "Ж 😀";'
  await page.getByLabel('Selected text', { exact: true }).fill(supplied)
  await page.getByLabel('Declared intent', { exact: true }).fill('Explain the state copied by this excerpt.')
  await page.getByLabel('Declared constraints', { exact: true }).fill('No complete repository was supplied.\nNo external disclosure.')
  await page.route('**/context/snapshots', route => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Temporary save failure', detail: 'Retry saving this version.' }) }) : route.continue(), { times: 1 })
  await previewAndSave(page)
  await expect(page.getByRole('alert')).toContainText('Retry saving this version')
  await expect(page.getByLabel('Selected text', { exact: true })).toHaveValue(supplied)
  await page.getByRole('button', { name: 'Save source snapshot', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Source version 1 saved')
  const first = (await (await page.request.get(account.root + '/snapshots')).json()).items[0]
  expect(first.source.excerpts[0].text).toBe(supplied)
  expect(first.disclosure.recipients).toHaveLength(0)
  expect(await page.evaluate(() => (window as Window & { contextExecuted?: boolean }).contextExecuted)).toBeUndefined()
  await page.getByLabel('Interpreted intent', { exact: true }).fill('Investigate value copying in this selected example.')
  await page.getByLabel('Interpreted constraints', { exact: true }).fill('Manual source only.')
  await page.getByLabel('Missing information', { exact: true }).fill('The production outcome is unknown.')
  await page.getByRole('button', { name: 'Save interpretation revision', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Interpretation saved separately')
  expect((await (await page.request.get(account.root)).json()).acceptedInterpretationId).toBeNull()
  await page.getByRole('button', { name: 'Review exact confirmation', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Confirm this exact interpretation?' })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('The production outcome is unknown.')
  await expect(dialog.getByRole('button', { name: 'Confirm source and interpretation' })).toBeDisabled()
  await page.keyboard.press('Tab')
  expect(await dialog.evaluate(element => element.contains(document.activeElement))).toBe(true)
  await dialog.getByLabel('I reviewed this source, interpretation and recorded missing information.').check()
  await dialog.getByRole('button', { name: 'Confirm source and interpretation' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText('User-confirmed exact revision', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Revise this interpretation' }).click()
  await page.getByLabel('Correction notes', { exact: true }).fill('Limit the interpretation to the supplied snippet.')
  await page.getByLabel('Interpreted intent', { exact: true }).fill('Discuss the snippet only.')
  await page.getByRole('button', { name: 'Save interpretation revision', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Interpretation saved separately')
  expect((await (await page.request.get(account.root)).json()).acceptedInterpretationId).toBeNull()
  expect((await (await page.request.get(account.root + `/snapshots/${first.id}`)).json()).sourceFingerprint).toBe(first.sourceFingerprint)
  await page.getByText('Prepare a new source version', { exact: true }).click()
  await page.getByLabel('Declared constraints', { exact: true }).fill('Changed constraint: inspect a new case.')
  await previewAndSave(page)
  await expect(page.getByRole('status')).toContainText('Source version 2 saved')
  await page.getByRole('button', { name: /^Version 1/ }).click()
  await expect(page.getByText('Version 1 · Historical', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review exact confirmation', exact: true })).toBeDisabled()
  await expect(page.getByText('Historical confirmation', { exact: false })).toBeVisible()
  expect((await (await page.request.get(account.root + '/snapshots')).json()).items).toHaveLength(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const previewButton = page.getByRole('button', { name: 'Preview selected context', exact: true })
  expect(await previewButton.evaluate(element => getComputedStyle(element).color)).toBe('rgb(255, 255, 255)')
  await page.screenshot({ path: info.outputPath('context-history-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Night appearance' }).click()
  await page.screenshot({ path: info.outputPath('context-history-night.png'), fullPage: true })
})

test('drafts survive navigation, appearance changes and stale-resource conflicts', async ({ page }, info) => {
  const account = await setup(page)
  const intent = 'Unsaved intent stays in this tab.'
  await page.getByLabel('Declared intent', { exact: true }).fill(intent)
  await page.getByRole('button', { name: 'Night appearance' }).click()
  await expect(page.getByLabel('Declared intent', { exact: true })).toHaveValue(intent)
  await page.getByRole('link', { name: 'All work episodes' }).click()
  await page.getByRole('link', { name: 'Review context' }).click()
  await expect(page.getByLabel('Declared intent', { exact: true })).toHaveValue(intent)
  await page.getByRole('button', { name: 'Preview selected context', exact: true }).click()
  await page.getByLabel('I reviewed these selected fields and recipients for this source version.').check()
  const preview = page.getByRole('region', { name: 'Disclosure preview' })
  await expect(preview).toContainText('External recipients: none.')
  const source = { kind: 'ManualWeb', excerpts: [{ label: 'Other tab', versionLabel: '', text: 'Competing selected input' }], intent: 'Other tab saved context', constraints: '' }
  const head = await (await page.request.get(account.root)).json()
  const otherPreview = await (await page.request.post(account.root + '/preview', { headers: { 'X-CSRF-Token': account.csrf }, data: { source } })).json()
  const otherSaved = await page.request.post(account.root + '/snapshots', { headers: { 'X-CSRF-Token': account.csrf, 'If-Match': `"${head.versionToken}"` },
    data: { operationId: crypto.randomUUID(), source, previewToken: otherPreview.previewToken } })
  expect(otherSaved.status()).toBe(201)
  await page.getByRole('button', { name: 'Save source snapshot', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Reload')
  await expect(page.getByLabel('Declared intent', { exact: true })).toHaveValue(intent)
  await page.getByRole('button', { name: 'Reload saved state' }).click()
  await expect(page.getByRole('button', { name: 'Save source snapshot', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Save source snapshot', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Source version 2 saved')
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('context-night-enlarged.png'), fullPage: true })
  await page.locator('.context-panel').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('context-night-enlarged-viewport.png') })
})
